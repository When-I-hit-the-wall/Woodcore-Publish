def _french_spaces(texts):
    """French sets a narrow no-break space before a colon, a semicolon, a question mark and an exclamation mark (docs/typst/language.md §4bis): written once here rather than in every sentence above."""
    out = {}
    for key, text in texts.items():
        for mark in (":", ";", "?", "!"):
            text = text.replace(" " + mark, " " + mark)
        out[key] = text
    return out


STRINGS["fr"] = _french_spaces(STRINGS["fr"])
