NNBSP = chr(0x202F)


def _french(text):
    """A French sentence with the narrow no-break space before `:`, `;`, `?`, `!` and inside «guillemets» -- written with ordinary spaces in the source below, where none can be told from a wrong one."""
    for mark in (":", ";", "?", "!"):
        text = text.replace(" " + mark, NNBSP + mark)
    return text.replace("« ", "«" + NNBSP).replace(" »", NNBSP + "»")


