TIPS = {"pan": "st_tip_pan", "line-load-linear": "st_tip_line_load_linear"}


def hint_key(tool):
    """The STRINGS key of what `tool` does, said in the drawing once it is chosen: a release's and a support's shared, every other tool's its own."""
    return HINTS.get(tool, "st_hint_release" if tool.startswith("release") else "st_hint_support")


def tip_key(tool):
    """The STRINGS key of how `tool` is used, under its name in its tooltip."""
    return TIPS.get(tool) or hint_key(tool)


