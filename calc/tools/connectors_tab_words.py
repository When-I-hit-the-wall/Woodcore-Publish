def _check_strings():
    reference = set(STRINGS["fr"])
    for lang, texts in STRINGS.items():
        missing, extra = reference - set(texts), set(texts) - reference
        if missing or extra:
            raise RuntimeError("connectors_tab.STRINGS[%r]: missing %s, extra %s"
                               % (lang, sorted(missing), sorted(extra)))
